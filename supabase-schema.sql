-- SAZU Academy Supabase schema
-- Run this entire file in Supabase Dashboard > SQL Editor.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'OTHER',
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  course text,
  status text not null default 'new' check (status in ('new','contacted','done')),
  created_at timestamptz not null default now()
);
create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name text not null,
  address text not null,
  phone text not null,
  created_at timestamptz not null default now()
);

create or replace function public.is_sazu_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admin_users where user_id = auth.uid()); $$;
revoke all on function public.is_sazu_admin() from public;
grant execute on function public.is_sazu_admin() to authenticated;

alter table public.admin_users enable row level security;
alter table public.courses enable row level security;
alter table public.leads enable row level security;
alter table public.branches enable row level security;

-- Admin roster is only readable by the signed-in admin themselves.
drop policy if exists "admins can read own admin record" on public.admin_users;
create policy "admins can read own admin record" on public.admin_users for select to authenticated using (user_id = auth.uid());
-- Public website can read active courses; only admins can manage them.
drop policy if exists "public can read active courses" on public.courses;
create policy "public can read active courses" on public.courses for select to anon, authenticated using (active = true or public.is_sazu_admin());
drop policy if exists "admins manage courses" on public.courses;
create policy "admins manage courses" on public.courses for all to authenticated using (public.is_sazu_admin()) with check (public.is_sazu_admin());
-- Public website may submit a lead; only admins can read/update/delete them.
drop policy if exists "public can submit leads" on public.leads;
create policy "public can submit leads" on public.leads for insert to anon, authenticated with check (length(trim(name)) > 0 and length(trim(phone)) > 0);
drop policy if exists "admins read leads" on public.leads;
create policy "admins read leads" on public.leads for select to authenticated using (public.is_sazu_admin());
drop policy if exists "admins update leads" on public.leads;
create policy "admins update leads" on public.leads for update to authenticated using (public.is_sazu_admin()) with check (public.is_sazu_admin());
drop policy if exists "admins delete leads" on public.leads;
create policy "admins delete leads" on public.leads for delete to authenticated using (public.is_sazu_admin());
-- Branches: public read; admin manage.
drop policy if exists "public read branches" on public.branches;
create policy "public read branches" on public.branches for select to anon, authenticated using (true);
drop policy if exists "admins manage branches" on public.branches;
create policy "admins manage branches" on public.branches for all to authenticated using (public.is_sazu_admin()) with check (public.is_sazu_admin());

-- Seed the initial course list only when the table is empty.
insert into public.courses (name, category)
select seed.name, seed.category from (values
 ('English','LANGUAGES'),('German','LANGUAGES'),('Russian','LANGUAGES'),('Turkish','LANGUAGES'),
 ('Matematika','SCIENCE'),('Robototexnika','TECHNOLOGY'),('Frontend','TECHNOLOGY')
) as seed(name,category)
where not exists (select 1 from public.courses);

